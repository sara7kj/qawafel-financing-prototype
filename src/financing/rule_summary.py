"""Automated analyst summary - rule-based (the default summary; no AI, no network, no key).

Built only from the exported package: it selects and labels values that are already
computed, adds the warnings and data limits, and asks follow-up questions triggered by
fixed rules. It computes no new financial figures and makes no approval or rejection.
"""

from __future__ import annotations

from decimal import Decimal

TITLE = "Automated analyst summary — rule-based"
NOTE = ("Generated by fixed rules from the computed results (no AI). It highlights figures, warnings and "
        "questions for the analyst; it is not a credit decision.")


# ---------------------------------------------------------------- display helpers (shared with ai_summary)

def sar(text: str | None) -> str | None:
    """'1150.00' -> 'SAR 1,150.00'; None stays None."""
    if text is None:
        return None
    amount = Decimal(text)
    return f"SAR {amount:,.2f}"


def pct(text: str | None) -> str | None:
    """A 4-decimal fraction string from the package, e.g. '0.3231' -> '32.31%'."""
    return None if text is None else f"{Decimal(text) * 100:.2f}%"


def data_limits(package: dict) -> list[str]:
    """Data limits built from the results: unverified collections, completeness, quality status, every N/A."""
    ind, dq, fin = package["indicators"], package["data_quality"], package["financing_estimate"]
    limits = ["Collections are payments recorded by the applicant; they are not reconciled to bank statements.",
              "Completeness of the source export is not verified (cannot be proven from dates alone)."]
    status = dq["receivables_quality_status"]
    limits.append(f"Receivables quality status: {status['value']}"
                  + (f" (reasons: {', '.join(status['reasons'])})." if status["reasons"] else "."))
    for key, label in (("gross_sales", "Gross sales"), ("credit_notes", "Credit notes"),
                       ("net_sales", "Net sales"), ("collections", "Collections")):
        for month, reason in ind[key]["na_reasons"].items():
            limits.append(f"{label} {month}: N/A - {reason}")
    if ind["credit_note_ratio"]["value"] is None:
        limits.append(f"Credit-note ratio: N/A - {ind['credit_note_ratio']['reason']}")
    if ind["receivables"]["reason"]:
        limits.append(f"Receivables aging: N/A - {ind['receivables']['reason']}")
    for key, label in (("sales_concentration", "Sales concentration"),
                       ("receivables_concentration", "Receivables concentration")):
        if ind[key]["top"] is None:
            limits.append(f"{label}: N/A - {ind[key]['reason']}")
    if fin["value"] is None:
        limits.append(f"Illustrative financing estimate: N/A - {fin['reason']}")
    return limits


# ---------------------------------------------------------------- summary

def _figure(label: str, value: str | None, reason: str | None = None, note: str | None = None) -> dict:
    return {"label": label, "value": value if value is not None else "N/A",
            "reason": reason if value is None else None, "note": note}


def _issue_rows(package: dict, rule: str) -> list[dict]:
    return [r for r in package["data_quality"]["issues"] if r["rule"] == rule]


def build_rule_summary(package: dict) -> dict:
    """Deterministic summary of an exported package (without any ai_summary)."""
    if package["status"]["blocked"]:
        return {
            "title": TITLE, "note": NOTE, "status": "blocked",
            "headline": "Analysis blocked: no figures are reported until the workbook problems are fixed.",
            "key_figures": [], "warnings": list(package["status"]["block_reasons"]),
            "data_limits": [],
            "follow_up_questions": ["Can the applicant provide a corrected workbook that fixes the blocking "
                                    "problems listed above?"],
        }

    ind, dq, fin = package["indicators"], package["data_quality"], package["financing_estimate"]
    rec, aging = ind["receivables"], ind["receivables"]["aging"]

    def total(key):
        series = ind[key]
        return sar(series["total"]), series["na_reasons"].get("total")

    figures = [
        _figure("Gross sales, reporting period (excl. VAT)", *total("gross_sales")),
        _figure("Net sales, reporting period (excl. VAT)", *total("net_sales")),
        _figure("Credit-note ratio (credit notes / gross sales)", pct(ind["credit_note_ratio"]["value"]),
                ind["credit_note_ratio"].get("reason")),
        _figure("Collections from accepted records only (incl. VAT)", *total("collections"),
                note="unverified; not comparable with sales (different VAT basis)"),
        _figure("Open receivables at the valuation date (incl. VAT)", sar(rec["total"]), rec["reason"],
                note=f"receivables quality: {rec['quality_status']}"),
        _figure("Open receivables more than 90 days overdue", sar(aging[">90"]) if aging else None, rec["reason"]),
        _figure(f"Illustrative financing estimate at {fin['advance_rate_percent']}%", sar(fin["value"]),
                fin["reason"], note="illustrative assumption - not a bank policy or credit decision"),
    ]
    for key, basis in (("sales_concentration", "net sales"), ("receivables_concentration", "open receivables")):
        conc = ind[key]
        if conc["top"] is None:
            figures.append(_figure(f"Largest customer by {basis}", None, conc["reason"]))
        else:
            top = conc["top"][0]
            figures.append(_figure(f"Largest customer by {basis}", f"{top['customer_id']} ({pct(top['share'])})"))

    warnings, questions = [], []
    for key, basis in (("sales_concentration", "net sales"), ("receivables_concentration", "open receivables")):
        conc = ind[key]
        for entry in conc["top"] or []:
            if entry["customer_id"] in conc["warnings"]:
                warnings.append(f"R-20: {entry['customer_id']} holds {pct(entry['share'])} of {basis} "
                                "(above the experimental 30% threshold - not a bank policy).")
                questions.append(f"How dependent is the business on {entry['customer_id']}, and what explains "
                                 f"its {pct(entry['share'])} share of {basis}?")

    status = dq["receivables_quality_status"]
    if status["value"] != "no_known_issues":
        warnings.append(f"Receivables quality: {status['value']} (reasons: {', '.join(status['reasons'])}).")
    if status["value"] == "unresolved_links":
        questions.append("Which invoices do the unlinked payments or credit notes belong to?")
    for entry in dq["receivable_unreliable_invoices"]:
        rules = ", ".join(dict.fromkeys(r["rule"] for r in entry["reasons"]))
        warnings.append(f"Invoice {entry['invoice_id']} is excluded from receivables ({rules}); "
                        "it stays in sales if its own data is sound.")
        questions.append(f"Can the applicant explain the settlements recorded against invoice "
                         f"{entry['invoice_id']} ({rules})?")

    counts = dq["record_counts_by_status"]
    quarantined = {s: counts[s]["quarantined"] for s in ("customers", "invoices", "payments", "credit_notes")}
    if any(quarantined.values()):
        parts = ", ".join(f"{n} {s.replace('_', ' ')}" for s, n in quarantined.items() if n)
        rules = sorted({r["rule"] for r in dq["issues"] if r["class"] == "QUARANTINE"})
        warnings.append(f"Quarantined records: {parts} (rules: {', '.join(rules)}). They are excluded and listed "
                        "in the issue table.")
        questions.append(f"Can the applicant correct the quarantined records ({', '.join(rules)})?")
    dependents = dq["dependent_payments_d13"]["records"]
    if dependents:
        warnings.append(f"{dependents} payment(s) excluded from collections because their invoice is "
                        "quarantined (D-13).")
    if counts["invoices"]["out_of_period"]:
        questions.append("Should open invoices issued before the reporting period be included in receivables?")

    if aging and Decimal(aging[">90"]) > 0:
        questions.append(f"What is the status of the {sar(aging['>90'])} more than 90 days overdue - disputed, "
                         "in collection, or expected to be paid?")
    empty_months = [r for r in _issue_rows(package, "R-19")]
    if empty_months:
        warnings.append(f"R-19: {len(empty_months)} month(s) in the reporting period have no invoices.")
        questions.append("Were there really no invoices in the empty months, or is the export incomplete?")
    for rule, text in (("R-17", "payment(s) or credit note(s) dated before their invoice"),
                       ("R-18", "customer record(s) share a name with another customer ID")):
        rows = _issue_rows(package, rule)
        if rows:
            warnings.append(f"{rule}: {len(rows)} {text}.")
    questions.append("Can the applicant provide bank statements for the reporting period, so that recorded "
                     "collections can be reconciled?")

    def phrase(figure, text):
        return f"{text} {figure['value']}" if figure["value"] != "N/A" else f"{text} N/A (see data limits)"

    headline = (f"{phrase(figures[1], 'Net sales of')} over the reporting period; "
                f"{phrase(figures[4], 'open receivables of')} at the valuation date; "
                f"receivables quality: {status['value']}.")
    return {"title": TITLE, "note": NOTE, "status": "ok", "headline": headline, "key_figures": figures,
            "warnings": warnings, "data_limits": data_limits(package), "follow_up_questions": questions}
